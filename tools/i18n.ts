#!/usr/bin/env bun
// Compiles i18n/*.json into i18n/dictionaries.ts, the only form the engine can load.
//   bun tools/i18n.ts           write i18n/dictionaries.ts
//   bun tools/i18n.ts --check   fail when it is stale, when the code uses a key en.json lacks,
//                               or when a dictionary has keys en.json does not, or misses some
import { readdir } from 'node:fs/promises'

const root = `${import.meta.dir}/..`
const dir = `${root}/i18n`
const target = `${dir}/dictionaries.ts`
const isCheck = process.argv.includes('--check')

const names = (await readdir(dir)).filter(name => name.endsWith('.json')).sort()
const dictionaries: Record<string, Record<string, string>> = {}
for (const name of names) dictionaries[name.replace(/\.json$/, '')] = await Bun.file(`${dir}/${name}`).json()

const english = dictionaries.en
if (english === undefined) throw new Error('i18n/en.json is missing: English is the fallback for every key')

const body =
  '// Generated by `bun tools/i18n.ts` from i18n/*.json: edit the JSON, then run it again.\n\n' +
  `export const DICTIONARIES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(dictionaries, null, 2)}\n`

const problems: string[] = []

// Every key a dictionary holds is one English holds, and the built-in ones hold all of English's.
for (const [language, words] of Object.entries(dictionaries)) {
  if (language === 'en') continue
  const extra = Object.keys(words).filter(key => !(key in english))
  const missing = Object.keys(english).filter(key => !(key in words))
  if (extra.length > 0) problems.push(`${language}.json has keys en.json lacks: ${extra.join(', ')}`)
  if (missing.length > 0) problems.push(`${language}.json misses: ${missing.join(', ')}`)
}

// Every literal key the code asks for is in English; tn() asks for `.one` and `.other`.
const sources = new Bun.Glob('{hooks,model,render,i18n,tools}/**/*.{ts,tsx}')
const used = new Set<string>()
for await (const file of sources.scan(root)) {
  if (file.endsWith('dictionaries.ts')) continue
  const text = await Bun.file(`${root}/${file}`).text()
  for (const m of text.matchAll(/\bt\(\s*'([^']+)'/g)) if (m[1]) used.add(m[1])
  for (const m of text.matchAll(/\btn\(\s*'([^']+)'/g)) if (m[1]) used.add(`${m[1]}.one`).add(`${m[1]}.other`)
}
const statusline = await Bun.file(`${root}/statusline.ts`).text()
for (const m of statusline.matchAll(/\bt\(\s*'([^']+)'/g)) if (m[1]) used.add(m[1])
const unknown = [...used].filter(key => !(key in english)).sort()
if (unknown.length > 0) problems.push(`the code uses keys en.json lacks: ${unknown.join(', ')}`)

if (isCheck) {
  const current = await Bun.file(target)
    .text()
    .catch(() => '')
  if (current !== body) problems.push('i18n/dictionaries.ts is stale: run `bun tools/i18n.ts`')
  if (problems.length > 0) {
    console.error(problems.map(p => `i18n: ${p}`).join('\n'))
    process.exit(1)
  }
  console.log(`i18n: ${names.length} dictionaries, ${Object.keys(english).length} keys, ${used.size} used by the code`)
} else {
  await Bun.write(target, body)
  for (const p of problems) console.warn(`i18n: ${p}`)
  console.log(`i18n: wrote ${target.replace(`${root}/`, '')} from ${names.join(', ')}`)
}
